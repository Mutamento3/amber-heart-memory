-- Initial public subset, based on the verified card/token schema.
-- __DIMENSIONS__ is substituted only after strict integer/range validation.
CREATE SCHEMA memory_core;
REVOKE ALL ON SCHEMA memory_core FROM PUBLIC;

CREATE TABLE memory_core.installation (
    version integer PRIMARY KEY CHECK (version = 1),
    settings jsonb NOT NULL,
    application_role text NOT NULL,
    migration_sha256 text NOT NULL,
    catalog_sha256 text NOT NULL,
    installed_at text NOT NULL
);

CREATE FUNCTION memory_core.format_timestamp(instant timestamptz)
RETURNS text LANGUAGE plpgsql STABLE SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
DECLARE
    zone text;
    local_time timestamp;
    offset_seconds integer;
BEGIN
    SELECT settings->>'timezone' INTO STRICT zone FROM memory_core.installation WHERE version = 1;
    local_time := instant AT TIME ZONE zone;
    offset_seconds := extract(epoch FROM (local_time - (instant AT TIME ZONE 'UTC')))::integer;
    RETURN to_char(local_time, 'YYYY-MM-DD"T"HH24:MI:SS')
        || CASE WHEN offset_seconds >= 0 THEN '+' ELSE '-' END
        || lpad((abs(offset_seconds) / 3600)::text, 2, '0') || ':'
        || lpad(((abs(offset_seconds) % 3600) / 60)::text, 2, '0');
END $$;

CREATE TABLE memory_core.memory_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL CHECK (btrim(bot_id) <> ''),
    content text NOT NULL,
    summary text,
    title text,
    item_kind text NOT NULL DEFAULT 'atomic' CHECK (item_kind IN ('atomic', 'topic_summary')),
    source_date text,
    embedding public.vector(__DIMENSIONS__),
    archive_reason text CHECK (archive_reason IN ('decay', 'gardener')),
    archived_at text,
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    updated_at text DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    UNIQUE (id, bot_id),
    CHECK ((archive_reason IS NULL) = (archived_at IS NULL)),
    CHECK (archive_reason IS NULL OR item_kind = 'atomic')
);

CREATE INDEX memory_items_space ON memory_core.memory_items (bot_id, item_kind);
CREATE INDEX memory_items_vector ON memory_core.memory_items
    USING hnsw (embedding public.vector_cosine_ops);

CREATE TABLE memory_core.memory_keyword_tokens (
    bot_id text NOT NULL,
    memory_id integer NOT NULL,
    field text NOT NULL CHECK (field IN (
        'title', 'summary', 'content', 'entity_name', 'entity_description', 'alias', 'topic_name'
    )),
    source_id integer NOT NULL CHECK (source_id > 0),
    term text NOT NULL CHECK (btrim(term) <> ''),
    term_frequency integer NOT NULL CHECK (term_frequency > 0),
    field_length integer NOT NULL CHECK (field_length > 0),
    updated_at text NOT NULL,
    PRIMARY KEY (memory_id, field, source_id, term),
    FOREIGN KEY (memory_id, bot_id) REFERENCES memory_core.memory_items (id, bot_id) ON DELETE CASCADE
);
CREATE INDEX memory_keyword_tokens_lookup ON memory_core.memory_keyword_tokens (bot_id, term, memory_id);

CREATE FUNCTION memory_core.set_semantic_updated_at()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
BEGIN
    IF ROW(NEW.content, NEW.summary, NEW.title, NEW.item_kind, NEW.source_date)
        IS DISTINCT FROM ROW(OLD.content, OLD.summary, OLD.title, OLD.item_kind, OLD.source_date) THEN
        NEW.updated_at := memory_core.format_timestamp(CURRENT_TIMESTAMP);
    ELSE
        NEW.updated_at := OLD.updated_at;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER memory_items_semantic_updated_at BEFORE UPDATE ON memory_core.memory_items
FOR EACH ROW EXECUTE FUNCTION memory_core.set_semantic_updated_at();

CREATE FUNCTION memory_core.replace_memory_keyword_tokens(
    target_memory_id integer, target_bot_id text, token_rows jsonb
) RETURNS integer LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
DECLARE inserted_count integer;
BEGIN
    IF token_rows IS NULL OR jsonb_typeof(token_rows) <> 'array' THEN
        RAISE EXCEPTION 'token_rows must be a JSON array';
    END IF;
    -- Serialize concurrent replacements and reject a card from another space.
    PERFORM 1 FROM memory_core.memory_items
        WHERE id = target_memory_id AND bot_id = target_bot_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'memory does not belong to the requested space';
    END IF;
    DELETE FROM memory_core.memory_keyword_tokens
        WHERE memory_id = target_memory_id AND bot_id = target_bot_id;
    INSERT INTO memory_core.memory_keyword_tokens
        (bot_id, memory_id, field, source_id, term, term_frequency, field_length, updated_at)
    SELECT target_bot_id, target_memory_id, field, source_id, lower(btrim(term)),
        term_frequency, field_length, updated_at
    FROM jsonb_to_recordset(token_rows) AS x(
        field text, source_id integer, term text, term_frequency integer, field_length integer, updated_at text
    );
    GET DIAGNOSTICS inserted_count = ROW_COUNT;
    RETURN inserted_count;
END $$;

CREATE FUNCTION memory_core.search_vectors(
    query_embedding public.vector, target_bot_id text, match_count integer,
    target_item_kind text, include_archived boolean
) RETURNS TABLE (id integer, content text, summary text, title text, source_date text, similarity double precision)
LANGUAGE sql STABLE SECURITY INVOKER SET search_path = pg_catalog, public, memory_core AS $$
    SELECT m.id, m.content, m.summary, m.title, m.source_date,
        (1 - (m.embedding <=> query_embedding))::double precision
    FROM memory_core.memory_items m
    WHERE m.bot_id = target_bot_id AND (include_archived OR m.archive_reason IS NULL)
        AND m.embedding IS NOT NULL AND (target_item_kind = 'all' OR m.item_kind = target_item_kind)
    ORDER BY m.embedding <=> query_embedding
    LIMIT greatest(0, match_count);
$$;

CREATE FUNCTION memory_core.search_keywords(
    query_text TEXT,
    target_bot_id TEXT,
    match_count INTEGER,
    target_item_kind TEXT,
    include_archived BOOLEAN
)
RETURNS TABLE (
    memory_id INTEGER,
    raw_score DOUBLE PRECISION,
    keyword_source TEXT,
    keyword_field TEXT,
    keyword_reason TEXT,
    matched_entity_id INTEGER,
    matched_topic_id INTEGER
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core
AS $function$
    WITH
    eligible_memories AS (
        SELECT mi.id
        FROM memory_core.memory_items AS mi
        WHERE mi.bot_id = target_bot_id
          AND (include_archived OR mi.archive_reason IS NULL)
          AND (
              target_item_kind = 'all'
              OR mi.item_kind = target_item_kind
          )
    ),
    query_terms AS (
        SELECT DISTINCT lower(trim(candidate)) AS term
        FROM unnest(
            regexp_split_to_array(
                COALESCE(query_text, ''),
                '[[:space:]]+OR[[:space:]]+',
                'i'
            )
        ) AS candidate
        WHERE trim(candidate) <> ''
          AND lower(trim(candidate)) <> 'or'
    ),
    document_stats AS (
        SELECT count(*)::DOUBLE PRECISION AS document_count
        FROM eligible_memories
    ),
    term_document_frequency AS (
        SELECT
            indexed.term,
            count(DISTINCT indexed.memory_id)::DOUBLE PRECISION AS document_frequency
        FROM memory_core.memory_keyword_tokens AS indexed
        JOIN eligible_memories AS eligible ON eligible.id = indexed.memory_id
        JOIN query_terms AS requested ON requested.term = indexed.term
        WHERE indexed.bot_id = target_bot_id
        GROUP BY indexed.term
    ),
    distinct_field_lengths AS (
        SELECT DISTINCT indexed.memory_id, indexed.field, indexed.field_length
        FROM memory_core.memory_keyword_tokens AS indexed
        JOIN eligible_memories AS eligible ON eligible.id = indexed.memory_id
        WHERE indexed.bot_id = target_bot_id
    ),
    average_field_lengths AS (
        SELECT
            lengths.field,
            sum(lengths.field_length)::DOUBLE PRECISION
                / NULLIF(stats.document_count, 0.0) AS average_length
        FROM distinct_field_lengths AS lengths
        CROSS JOIN document_stats AS stats
        GROUP BY lengths.field, stats.document_count
    ),
    grouped_hits AS (
        SELECT
            indexed.memory_id,
            indexed.field,
            indexed.term,
            sum(indexed.term_frequency)::DOUBLE PRECISION AS term_frequency,
            max(indexed.field_length)::DOUBLE PRECISION AS field_length,
            min(indexed.source_id)::INTEGER AS source_id
        FROM memory_core.memory_keyword_tokens AS indexed
        JOIN eligible_memories AS eligible ON eligible.id = indexed.memory_id
        JOIN query_terms AS requested ON requested.term = indexed.term
        WHERE indexed.bot_id = target_bot_id
        GROUP BY indexed.memory_id, indexed.field, indexed.term
    ),
    scored_components AS (
        SELECT
            hit.memory_id,
            hit.field,
            hit.term,
            hit.source_id,
            (
                CASE hit.field
                    WHEN 'title' THEN 1.00
                    WHEN 'summary' THEN 0.85
                    WHEN 'content' THEN 0.70
                    WHEN 'entity_name' THEN 0.95
                    WHEN 'entity_description' THEN 0.70
                    WHEN 'alias' THEN 0.60
                    WHEN 'topic_name' THEN 0.80
                    ELSE 0.0
                END
                * ln(
                    1.0 + (
                        stats.document_count - frequency.document_frequency + 0.5
                    ) / (frequency.document_frequency + 0.5)
                )
                * (
                    hit.term_frequency * 2.2
                    / NULLIF(
                        hit.term_frequency
                        + 1.2 * (
                            0.25
                            + 0.75 * hit.field_length
                                / NULLIF(average.average_length, 0.0)
                        ),
                        0.0
                    )
                )
            )::DOUBLE PRECISION AS component_score
        FROM grouped_hits AS hit
        JOIN term_document_frequency AS frequency ON frequency.term = hit.term
        JOIN average_field_lengths AS average ON average.field = hit.field
        CROSS JOIN document_stats AS stats
        WHERE stats.document_count > 0
    )
    SELECT
        component.memory_id,
        sum(component.component_score)::DOUBLE PRECISION AS raw_score,
        (array_agg(
            CASE
                WHEN component.field IN ('entity_name', 'entity_description', 'alias') THEN 'entity'
                WHEN component.field = 'topic_name' THEN 'topic'
                ELSE 'memory_direct'
            END
            ORDER BY component.component_score DESC, component.field, component.term
        ))[1]::TEXT AS keyword_source,
        (array_agg(
            component.field
            ORDER BY component.component_score DESC, component.field, component.term
        ))[1]::TEXT AS keyword_field,
        (array_agg(
            'BM25 ' || component.field || ' 命中：' || component.term
            ORDER BY component.component_score DESC, component.field, component.term
        ))[1]::TEXT AS keyword_reason,
        (array_agg(
            CASE
                WHEN component.field IN ('entity_name', 'entity_description', 'alias')
                    THEN component.source_id
                ELSE NULL
            END
            ORDER BY component.component_score DESC, component.field, component.term
        ) FILTER (
            WHERE component.field IN ('entity_name', 'entity_description', 'alias')
        ))[1]::INTEGER AS matched_entity_id,
        (array_agg(
            CASE WHEN component.field = 'topic_name' THEN component.source_id ELSE NULL END
            ORDER BY component.component_score DESC, component.field, component.term
        ) FILTER (WHERE component.field = 'topic_name'))[1]::INTEGER AS matched_topic_id
    FROM scored_components AS component
    GROUP BY component.memory_id
    ORDER BY sum(component.component_score) DESC, component.memory_id DESC
    LIMIT greatest(0, match_count);
$function$;

