CREATE FUNCTION memory_core.normalize_entity_name(value text)
RETURNS text LANGUAGE plpgsql IMMUTABLE STRICT SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
DECLARE
    result text := lower(normalize(btrim(value), NFKC));
    openings text[] := ARRAY['《','〈','「','『','“','‘','"','''','(','[','【'];
    closings text[] := ARRAY['》','〉','」','』','”','’','"','''',')',']','】'];
    changed boolean;
    i integer;
BEGIN
    LOOP
        changed := false;
        FOR i IN 1..cardinality(openings) LOOP
            IF length(result) >= 2 AND left(result,1)=openings[i] AND right(result,1)=closings[i] THEN
                result := btrim(substr(result,2,length(result)-2));
                changed := true;
                EXIT;
            END IF;
        END LOOP;
        EXIT WHEN NOT changed;
    END LOOP;
    RETURN regexp_replace(result, '[[:space:]]+', '', 'g');
END $$;

CREATE FUNCTION memory_core.entity_lookup_keys(name text, aliases text[])
RETURNS text[] LANGUAGE sql IMMUTABLE SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
    SELECT coalesce(array_agg(key ORDER BY key), '{}'::text[])
    FROM (SELECT DISTINCT memory_core.normalize_entity_name(value) AS key
          FROM unnest(ARRAY[name] || coalesce(aliases,'{}'::text[])) value) keys
    WHERE key IS NOT NULL AND key <> '';
$$;

CREATE FUNCTION memory_core.valid_string_array(values_to_check text[])
RETURNS boolean LANGUAGE sql IMMUTABLE SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
    SELECT values_to_check IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM unnest(values_to_check) value
        WHERE value IS NULL OR memory_core.normalize_entity_name(value) = ''
    );
$$;

