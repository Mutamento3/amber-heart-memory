CREATE FUNCTION memory_core.guard_entity_configuration()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
DECLARE space text; eid integer; managed boolean;
BEGIN
    space := CASE WHEN TG_OP='DELETE' THEN OLD.bot_id ELSE NEW.bot_id END;
    eid := CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END;
    SELECT eid IN (p.user_entity_id,p.assistant_entity_id) INTO managed
        FROM memory_core.space_policies p WHERE p.bot_id=space;
    IF current_user <> (SELECT pg_get_userbyid(nspowner) FROM pg_namespace WHERE nspname='memory_core')
       AND (coalesce(managed,false) OR (TG_OP <> 'DELETE' AND NEW.entity_key LIKE 'participant:%')) THEN
        RAISE EXCEPTION 'participant entities require configuration-owner privileges' USING ERRCODE='42501';
    END IF;
    IF TG_OP <> 'DELETE' THEN
        IF TG_OP='UPDATE' AND (NEW.bot_id<>OLD.bot_id OR NEW.entity_key<>OLD.entity_key) THEN
            RAISE EXCEPTION 'entity identity and space are immutable';
        END IF;
        RETURN NEW;
    END IF;
    RETURN OLD;
END $$;
CREATE TRIGGER entity_configuration_guard BEFORE INSERT OR UPDATE OR DELETE ON memory_core.entities
FOR EACH ROW EXECUTE FUNCTION memory_core.guard_entity_configuration();

CREATE FUNCTION memory_core.check_space_policy(p memory_core.space_policies)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
DECLARE u memory_core.entities; a memory_core.entities;
BEGIN
    IF p.user_entity_id IS NOT NULL THEN
        SELECT * INTO u FROM memory_core.entities WHERE id=p.user_entity_id AND bot_id=p.bot_id;
        SELECT * INTO a FROM memory_core.entities WHERE id=p.assistant_entity_id AND bot_id=p.bot_id;
        IF u.id IS NULL OR a.id IS NULL OR u.entity_type<>'PERSON' OR a.entity_type<>'PERSON'
           OR u.lookup_keys && a.lookup_keys THEN
            RAISE EXCEPTION 'participants must be two distinct PERSON entities in this space';
        END IF;
        IF EXISTS (SELECT 1 FROM memory_core.entities e WHERE e.bot_id=p.bot_id
            AND e.id NOT IN (u.id,a.id) AND e.lookup_keys && (u.lookup_keys || a.lookup_keys)) THEN
            RAISE EXCEPTION 'entity name or alias conflicts with a participant';
        END IF;
    END IF;
    IF EXISTS (SELECT 1 FROM memory_core.entities e WHERE e.bot_id=p.bot_id
        AND e.lookup_keys && memory_core.entity_lookup_keys('',p.ignored_terms)) THEN
        RAISE EXCEPTION 'address-only terms conflict with entity names or aliases';
    END IF;
END $$;

CREATE FUNCTION memory_core.validate_space_policy()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended('space-config:' || NEW.bot_id,0));
    PERFORM memory_core.check_space_policy(NEW);
    IF TG_OP='UPDATE' THEN
        IF NEW.bot_id<>OLD.bot_id OR NEW.revision<OLD.revision OR NEW.revision>OLD.revision+1 THEN
            RAISE EXCEPTION 'invalid configuration identity or revision';
        END IF;
        IF ROW(NEW.user_entity_id,NEW.assistant_entity_id,NEW.ignored_terms,NEW.source_retention_days,NEW.topic_template)
            IS DISTINCT FROM ROW(OLD.user_entity_id,OLD.assistant_entity_id,OLD.ignored_terms,OLD.source_retention_days,OLD.topic_template)
            AND OLD.user_entity_id IS NOT NULL THEN
            NEW.revision := OLD.revision+1;
        END IF;
        NEW.updated_at := memory_core.format_timestamp(CURRENT_TIMESTAMP);
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER space_policy_validation BEFORE INSERT OR UPDATE ON memory_core.space_policies
FOR EACH ROW EXECUTE FUNCTION memory_core.validate_space_policy();

CREATE FUNCTION memory_core.check_entity_policy_final()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
DECLARE p memory_core.space_policies;
BEGIN
    PERFORM pg_advisory_xact_lock_shared(hashtextextended('space-config:' ||
        CASE WHEN TG_OP='DELETE' THEN OLD.bot_id ELSE NEW.bot_id END,0));
    SELECT * INTO p FROM memory_core.space_policies
        WHERE bot_id=CASE WHEN TG_OP='DELETE' THEN OLD.bot_id ELSE NEW.bot_id END;
    IF p.bot_id IS NOT NULL THEN PERFORM memory_core.check_space_policy(p); END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER entity_policy_final AFTER INSERT OR UPDATE OR DELETE ON memory_core.entities
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION memory_core.check_entity_policy_final();

CREATE FUNCTION memory_core.graph_seed_entities(space text, candidates integer[], expected_revision bigint)
RETURNS integer[] LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
DECLARE p memory_core.space_policies; result integer[];
BEGIN
    PERFORM pg_advisory_xact_lock_shared(hashtextextended('space-config:' || space,0));
    SELECT * INTO p FROM memory_core.space_policies WHERE bot_id=space;
    IF p.bot_id IS NULL OR p.user_entity_id IS NULL THEN RAISE EXCEPTION 'space is not configured'; END IF;
    IF p.revision<>expected_revision THEN RAISE EXCEPTION 'configuration changed' USING ERRCODE='40001'; END IF;
    IF candidates IS NULL OR EXISTS(SELECT 1 FROM unnest(candidates) candidate
        LEFT JOIN memory_core.entities e ON e.id=candidate AND e.bot_id=space WHERE e.id IS NULL) THEN
        RAISE EXCEPTION 'unknown or cross-space graph seed';
    END IF;
    SELECT coalesce(array_agg(id ORDER BY first_position),'{}'::integer[]) INTO result
    FROM (SELECT candidate AS id,min(position) AS first_position
        FROM unnest(candidates) WITH ORDINALITY AS x(candidate,position)
        WHERE candidate NOT IN (p.user_entity_id,p.assistant_entity_id) GROUP BY candidate) accepted;
    RETURN result;
END $$;

CREATE OR REPLACE FUNCTION memory_core.set_semantic_updated_at()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, memory_core AS $$
BEGIN
    IF ROW(NEW.content,NEW.summary,NEW.title,NEW.item_kind,NEW.source_date,NEW.is_milestone,
        NEW.decay_layer,NEW.valence,NEW.arousal,NEW.cognitive_status,NEW.source_type,
        NEW.source_kind,NEW.experience_mode,NEW.primary_topic_id,NEW.parent_reflection_id,NEW.child_episode_ids)
      IS DISTINCT FROM ROW(OLD.content,OLD.summary,OLD.title,OLD.item_kind,OLD.source_date,OLD.is_milestone,
        OLD.decay_layer,OLD.valence,OLD.arousal,OLD.cognitive_status,OLD.source_type,
        OLD.source_kind,OLD.experience_mode,OLD.primary_topic_id,OLD.parent_reflection_id,OLD.child_episode_ids) THEN
        NEW.updated_at := memory_core.format_timestamp(CURRENT_TIMESTAMP);
    ELSE NEW.updated_at := OLD.updated_at;
    END IF;
    RETURN NEW;
END $$;

