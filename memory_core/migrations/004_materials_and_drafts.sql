ALTER TABLE memory_core.space_policies
    ADD COLUMN minimum_importance integer NOT NULL DEFAULT 7 CHECK (minimum_importance BETWEEN 1 AND 10),
    ADD COLUMN daily_limit integer NOT NULL DEFAULT 5 CHECK (daily_limit > 0),
    ADD COLUMN core_facts text[] NOT NULL DEFAULT '{}' CHECK (memory_core.valid_string_array(core_facts));

-- A tombstone keeps provenance and idempotency after the original is removed.
CREATE TABLE memory_core.source_materials (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL REFERENCES memory_core.space_policies(bot_id),
    source_key text NOT NULL CHECK (btrim(source_key)<>''),
    content_sha256 text NOT NULL,
    business_date text NOT NULL CHECK (business_date ~ '^\d{4}-\d{2}-\d{2}$'),
    source_kind text NOT NULL CHECK (source_kind IN ('mainline','chatroom','coreading')),
    segments jsonb,
    deleted_at text,
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    CHECK ((segments IS NULL)=(deleted_at IS NOT NULL)),
    CHECK (segments IS NULL OR jsonb_typeof(segments)='array'),
    UNIQUE(bot_id,source_key), UNIQUE(id,bot_id)
);
CREATE INDEX source_materials_retention ON memory_core.source_materials(bot_id,created_at) WHERE deleted_at IS NULL;

CREATE TABLE memory_core.material_extractions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL,
    material_id integer NOT NULL,
    request_key text NOT NULL CHECK (btrim(request_key)<>''),
    policy_revision bigint NOT NULL CHECK (policy_revision>0),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','selected','complete','failed')),
    version integer NOT NULL DEFAULT 1 CHECK (version>0),
    error_code text,
    skipped_reason text,
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    updated_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    UNIQUE(bot_id,material_id), UNIQUE(bot_id,request_key), UNIQUE(id,bot_id),
    FOREIGN KEY(material_id,bot_id) REFERENCES memory_core.source_materials(id,bot_id)
);

CREATE TABLE memory_core.pending_memories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL,
    extraction_id integer NOT NULL,
    ordinal integer NOT NULL CHECK (ordinal>=0),
    business_date text NOT NULL,
    policy_revision bigint NOT NULL CHECK (policy_revision>0),
    version integer NOT NULL DEFAULT 1 CHECK (version>0),
    narrative jsonb NOT NULL CHECK (jsonb_typeof(narrative)='object'),
    payload jsonb,
    status text NOT NULL DEFAULT 'structure_pending'
        CHECK (status IN ('structure_pending','structure_failed','pending','rejected')),
    error_code text,
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    updated_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    UNIQUE(bot_id,extraction_id,ordinal), UNIQUE(id,bot_id),
    CHECK (payload IS NULL OR jsonb_typeof(payload)='object'),
    CHECK (status<>'pending' OR payload IS NOT NULL),
    FOREIGN KEY(extraction_id,bot_id) REFERENCES memory_core.material_extractions(id,bot_id)
);
CREATE INDEX pending_memories_daily_quota ON memory_core.pending_memories(bot_id,business_date);
CREATE INDEX pending_memories_review ON memory_core.pending_memories(bot_id,status,id);
