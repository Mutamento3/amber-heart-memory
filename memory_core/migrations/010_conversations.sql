-- Conversation retention is independent of imported source retention.
ALTER TABLE memory_core.space_policies ADD COLUMN conversation_retention_days integer
    DEFAULT 30 CHECK (conversation_retention_days > 0);

CREATE TABLE memory_core.conversation_turns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL REFERENCES memory_core.space_policies(bot_id),
    position_id bigint NOT NULL,
    replaces_turn_id bigint,
    anchor_message_id bigint,
    anchor_kind text NOT NULL DEFAULT 'unclassified'
        CHECK (anchor_kind IN ('unclassified','matched','absent','unmatched')),
    generation_state text NOT NULL DEFAULT 'pending'
        CHECK (generation_state IN ('pending','generating','waiting_tools','complete','failed','incomplete')),
    history_state text NOT NULL DEFAULT 'current'
        CHECK (history_state IN ('current','candidate','replaced')),
    business_date text NOT NULL CHECK (business_date ~ '^\d{4}-\d{2}-\d{2}$'),
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    finished_at text,
    history_changed_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    frozen_context jsonb CHECK (frozen_context IS NULL OR jsonb_typeof(frozen_context)='object'),
    context_manifest jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(context_manifest)='object'),
    recall_snapshot jsonb NOT NULL DEFAULT '{"status":"not_run","cards":[]}'
        CHECK (jsonb_typeof(recall_snapshot)='object'),
    content_deleted_at text,
    UNIQUE(id,bot_id),
    FOREIGN KEY(position_id,bot_id) REFERENCES memory_core.conversation_turns(id,bot_id) DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY(replaces_turn_id,bot_id) REFERENCES memory_core.conversation_turns(id,bot_id),
    CHECK (replaces_turn_id IS NULL OR replaces_turn_id<>id),
    CHECK (content_deleted_at IS NULL OR frozen_context IS NULL)
);
CREATE UNIQUE INDEX conversation_one_current_version ON memory_core.conversation_turns(bot_id,position_id)
    WHERE history_state='current';
CREATE INDEX conversation_history ON memory_core.conversation_turns(bot_id,business_date,position_id)
    WHERE history_state='current' AND content_deleted_at IS NULL;
CREATE INDEX conversation_retention ON memory_core.conversation_turns(bot_id,created_at)
    WHERE content_deleted_at IS NULL;

CREATE TABLE memory_core.conversation_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL,
    turn_id bigint NOT NULL,
    step_index integer NOT NULL CHECK (step_index>=0),
    client_request_id text CHECK (client_request_id IS NULL OR (length(client_request_id) BETWEEN 1 AND 128)),
    client_operation text CHECK (client_operation IN ('new','retry','regenerate','edit')),
    target_turn_id bigint,
    resolved_operation text NOT NULL DEFAULT 'development_unclassified'
        CHECK (resolved_operation IN ('development_unclassified','new','retry','regenerate','edit','tool_continue')),
    retry_of_request_id bigint,
    request_fingerprint text NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    model text NOT NULL CHECK (length(model) BETWEEN 1 AND 256),
    stream boolean NOT NULL,
    upstream_response_id text,
    state text NOT NULL DEFAULT 'pending'
        CHECK (state IN ('pending','requesting','complete','upstream_failed','interrupted','archive_failed')),
    finish_reason text,
    usage jsonb CHECK (usage IS NULL OR jsonb_typeof(usage)='object'),
    usage_receipt jsonb NOT NULL DEFAULT '{"status":"not_run","counted":false}' CHECK (jsonb_typeof(usage_receipt)='object'),
    error_stage text,
    error_code text,
    started_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    finished_at text,
    UNIQUE(id,bot_id), UNIQUE(id,turn_id,bot_id), UNIQUE(bot_id,client_request_id), UNIQUE(turn_id,step_index),
    FOREIGN KEY(turn_id,bot_id) REFERENCES memory_core.conversation_turns(id,bot_id),
    FOREIGN KEY(target_turn_id,bot_id) REFERENCES memory_core.conversation_turns(id,bot_id),
    FOREIGN KEY(retry_of_request_id,bot_id) REFERENCES memory_core.conversation_requests(id,bot_id)
);

CREATE TABLE memory_core.conversation_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL,
    turn_id bigint NOT NULL,
    request_id bigint NOT NULL,
    event_index integer NOT NULL CHECK (event_index>=0),
    role text NOT NULL CHECK (role IN ('user','assistant')),
    content_parts jsonb CHECK (content_parts IS NULL OR jsonb_typeof(content_parts)='array'),
    match_fingerprint text CHECK (match_fingerprint ~ '^[0-9a-f]{64}$'),
    content_state text NOT NULL CHECK (content_state IN ('complete','incomplete')),
    occurred_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    content_deleted_at text,
    UNIQUE(id,bot_id), UNIQUE(turn_id,event_index),
    FOREIGN KEY(request_id,turn_id,bot_id) REFERENCES memory_core.conversation_requests(id,turn_id,bot_id),
    CHECK ((content_parts IS NULL)=(content_deleted_at IS NOT NULL)),
    CHECK (content_deleted_at IS NULL OR match_fingerprint IS NULL)
);
ALTER TABLE memory_core.conversation_turns ADD CONSTRAINT conversation_anchor_space
    FOREIGN KEY(anchor_message_id,bot_id) REFERENCES memory_core.conversation_messages(id,bot_id);

CREATE TABLE memory_core.conversation_tool_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL,
    turn_id bigint NOT NULL,
    request_id bigint NOT NULL,
    event_index integer NOT NULL CHECK (event_index>=0),
    kind text NOT NULL CHECK (kind IN ('call','result')),
    tool_call_id text NOT NULL CHECK (length(tool_call_id) BETWEEN 1 AND 256),
    tool_name text,
    payload jsonb,
    reported_status text NOT NULL DEFAULT 'unknown' CHECK (reported_status IN ('unknown','success','failure')),
    occurred_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    content_deleted_at text,
    UNIQUE(turn_id,event_index), UNIQUE(turn_id,kind,tool_call_id),
    FOREIGN KEY(request_id,turn_id,bot_id) REFERENCES memory_core.conversation_requests(id,turn_id,bot_id),
    CHECK ((payload IS NULL)=(content_deleted_at IS NOT NULL))
);

CREATE TABLE memory_core.conversation_space_state (
    bot_id text PRIMARY KEY REFERENCES memory_core.space_policies(bot_id),
    active_turn_id bigint,
    active_request_id bigint,
    lease_token uuid,
    lease_expires_at text,
    history_revision bigint NOT NULL DEFAULT 0 CHECK (history_revision>=0),
    updated_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    FOREIGN KEY(active_turn_id,bot_id) REFERENCES memory_core.conversation_turns(id,bot_id),
    FOREIGN KEY(active_request_id,active_turn_id,bot_id) REFERENCES memory_core.conversation_requests(id,turn_id,bot_id),
    CHECK ((active_turn_id IS NULL)=(lease_token IS NULL)),
    CHECK ((active_turn_id IS NULL)=(lease_expires_at IS NULL)),
    CHECK (active_request_id IS NULL OR active_turn_id IS NOT NULL)
);
REVOKE ALL ON ALL TABLES IN SCHEMA memory_core FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA memory_core FROM PUBLIC;
