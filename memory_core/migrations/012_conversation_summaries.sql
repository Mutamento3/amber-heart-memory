-- Exact turn-version coverage; no dependence on a maximum message identifier.
ALTER TABLE memory_core.conversation_turns ADD CONSTRAINT conversation_turn_day
    UNIQUE(id,bot_id,business_date);

CREATE TABLE memory_core.conversation_summaries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL REFERENCES memory_core.space_policies(bot_id),
    business_date text NOT NULL CHECK (business_date ~ '^\d{4}-\d{2}-\d{2}$'),
    level smallint NOT NULL CHECK (level IN (1,2)),
    content text,
    model text NOT NULL CHECK (length(model) BETWEEN 1 AND 256),
    usage jsonb CHECK (usage IS NULL OR jsonb_typeof(usage)='object'),
    source_revision bigint NOT NULL CHECK (source_revision>=0),
    source_digest text NOT NULL CHECK (source_digest ~ '^[0-9a-f]{64}$'),
    start_at text NOT NULL,
    end_at text NOT NULL,
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    content_deleted_at text,
    first_summary_id bigint,
    second_summary_id bigint,
    third_summary_id bigint,
    merged_into_id bigint,
    UNIQUE(id,bot_id,business_date),
    UNIQUE(id,bot_id,business_date,level),
    UNIQUE(bot_id,first_summary_id),
    FOREIGN KEY(first_summary_id,bot_id,business_date)
        REFERENCES memory_core.conversation_summaries(id,bot_id,business_date),
    FOREIGN KEY(second_summary_id,bot_id,business_date)
        REFERENCES memory_core.conversation_summaries(id,bot_id,business_date),
    FOREIGN KEY(third_summary_id,bot_id,business_date)
        REFERENCES memory_core.conversation_summaries(id,bot_id,business_date),
    FOREIGN KEY(merged_into_id,bot_id,business_date)
        REFERENCES memory_core.conversation_summaries(id,bot_id,business_date),
    CHECK ((content IS NULL)=(content_deleted_at IS NOT NULL)),
    CHECK (content IS NULL OR length(btrim(content))>0),
    CHECK ((level=1 AND first_summary_id IS NULL AND second_summary_id IS NULL AND third_summary_id IS NULL)
        OR (level=2 AND first_summary_id IS NOT NULL AND second_summary_id IS NOT NULL
            AND third_summary_id IS NOT NULL AND first_summary_id<second_summary_id AND second_summary_id<third_summary_id)),
    CHECK (merged_into_id IS NULL OR (level=1 AND merged_into_id<>id))
);
CREATE INDEX conversation_summary_day ON memory_core.conversation_summaries(bot_id,business_date,id)
    WHERE content_deleted_at IS NULL;
CREATE INDEX conversation_summary_merged ON memory_core.conversation_summaries(merged_into_id,bot_id,business_date)
    WHERE merged_into_id IS NOT NULL;
CREATE INDEX conversation_summary_second ON memory_core.conversation_summaries(second_summary_id,bot_id,business_date)
    WHERE second_summary_id IS NOT NULL;
CREATE INDEX conversation_summary_third ON memory_core.conversation_summaries(third_summary_id,bot_id,business_date)
    WHERE third_summary_id IS NOT NULL;

CREATE TABLE memory_core.conversation_summary_turns (
    summary_id bigint NOT NULL,
    bot_id text NOT NULL,
    business_date text NOT NULL,
    level smallint NOT NULL DEFAULT 1 CHECK (level=1),
    turn_id bigint NOT NULL,
    PRIMARY KEY(summary_id,turn_id),
    UNIQUE(bot_id,turn_id),
    FOREIGN KEY(summary_id,bot_id,business_date,level)
        REFERENCES memory_core.conversation_summaries(id,bot_id,business_date,level),
    FOREIGN KEY(turn_id,bot_id,business_date)
        REFERENCES memory_core.conversation_turns(id,bot_id,business_date)
);
REVOKE ALL ON memory_core.conversation_summaries,memory_core.conversation_summary_turns FROM PUBLIC;
REVOKE ALL ON SEQUENCE memory_core.conversation_summaries_id_seq FROM PUBLIC;
