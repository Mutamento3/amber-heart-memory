-- Each diary is a durable derivative; raw-data retention does not delete it.
CREATE TABLE memory_core.conversation_diaries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL REFERENCES memory_core.space_policies(bot_id),
    business_date text NOT NULL CHECK (business_date ~ '^\d{4}-\d{2}-\d{2}$'),
    content text NOT NULL CHECK (length(btrim(content))>0),
    revision bigint NOT NULL DEFAULT 1 CHECK (revision>0),
    user_edited boolean NOT NULL DEFAULT false,
    edited_at text,
    source_revision bigint NOT NULL CHECK (source_revision>=0),
    source_digest text NOT NULL CHECK (source_digest ~ '^[0-9a-f]{64}$'),
    source_turn_ids bigint[] NOT NULL CHECK (cardinality(source_turn_ids)>0 AND array_position(source_turn_ids,NULL) IS NULL),
    model text NOT NULL CHECK (length(model) BETWEEN 1 AND 256),
    usage jsonb CHECK (usage IS NULL OR jsonb_typeof(usage)='object'),
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    updated_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    UNIQUE(bot_id,business_date),
    CHECK (user_edited=(edited_at IS NOT NULL))
);

-- Kinds are extensible; only registered server-side handlers may execute them.
CREATE TABLE memory_core.daily_tasks (
    bot_id text NOT NULL REFERENCES memory_core.space_policies(bot_id),
    task_kind text NOT NULL CHECK (task_kind ~ '^[a-z][a-z0-9_]{0,39}$'),
    business_date text NOT NULL CHECK (business_date ~ '^\d{4}-\d{2}-\d{2}$'),
    state text NOT NULL CHECK (state IN ('running','done','skipped','failed')),
    attempts bigint NOT NULL CHECK (attempts>0),
    last_error_code text CHECK (last_error_code ~ '^[a-zA-Z0-9_:-]{1,100}$'),
    result jsonb CHECK (result IS NULL OR jsonb_typeof(result)='object'),
    retry_at text,
    started_at text NOT NULL,
    finished_at text,
    updated_at text NOT NULL,
    PRIMARY KEY(bot_id,task_kind,business_date),
    CHECK ((state='failed')=(retry_at IS NOT NULL)),
    CHECK ((state='running')=(finished_at IS NULL))
);
CREATE INDEX daily_tasks_retry ON memory_core.daily_tasks(bot_id,retry_at)
    WHERE state='failed';
REVOKE ALL ON memory_core.conversation_diaries,memory_core.daily_tasks FROM PUBLIC;
REVOKE ALL ON SEQUENCE memory_core.conversation_diaries_id_seq FROM PUBLIC;
