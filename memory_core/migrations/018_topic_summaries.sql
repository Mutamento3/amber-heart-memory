-- Summaries now share normal archival; absorbed children remain protected by
-- memory_items_check3 (archive_reason IS NULL OR parent_reflection_id IS NULL).
ALTER TABLE memory_core.memory_items DROP CONSTRAINT memory_items_check1;

CREATE TABLE memory_core.topic_summary_batches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL REFERENCES memory_core.space_policies(bot_id),
    topic_id integer NOT NULL,
    cycle_date text NOT NULL CHECK (cycle_date ~ '^\d{4}-\d{2}-03$'),
    window_start text NOT NULL CHECK (window_start ~ '^\d{4}-\d{2}$'),
    window_end text NOT NULL CHECK (window_end ~ '^\d{4}-\d{2}$' AND window_end>=window_start),
    request_key text NOT NULL CHECK (request_key ~ '^[0-9a-f]{64}$'),
    policy_revision bigint NOT NULL CHECK (policy_revision>0),
    context_digest text NOT NULL CHECK (context_digest ~ '^[0-9a-f]{64}$'),
    status text NOT NULL DEFAULT 'generating' CHECK (status IN ('generating','failed','pending','approved','rejected','revoked','empty')),
    version integer NOT NULL DEFAULT 1 CHECK (version>0),
    title text NOT NULL DEFAULT '',
    content text NOT NULL DEFAULT '',
    model text,
    model_usage jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(model_usage)='array'),
    review_ready_at text,
    reviewed_at text,
    review_key text,
    summary_card_id integer UNIQUE,
    reconsider_at text,
    error_code text,
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    updated_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    UNIQUE(id,bot_id), UNIQUE(bot_id,request_key), UNIQUE(bot_id,review_key),
    FOREIGN KEY(topic_id,bot_id) REFERENCES memory_core.topics(id,bot_id),
    FOREIGN KEY(summary_card_id,bot_id) REFERENCES memory_core.memory_items(id,bot_id),
    CHECK ((status='approved')=(summary_card_id IS NOT NULL)),
    CHECK (status NOT IN ('pending','approved') OR (btrim(title)<>'' AND btrim(content)<>'' AND review_ready_at IS NOT NULL)),
    CHECK (status<>'revoked' OR (title='' AND content=''))
);
CREATE INDEX topic_summary_review ON memory_core.topic_summary_batches(bot_id,review_ready_at)
    WHERE status='pending';
CREATE INDEX topic_summary_windows ON memory_core.topic_summary_batches(bot_id,topic_id,window_start,window_end);

CREATE TABLE memory_core.topic_summary_sources (
    batch_id integer NOT NULL,
    bot_id text NOT NULL,
    ordinal integer NOT NULL CHECK (ordinal>=0),
    memory_id integer,
    source_hash text CHECK (source_hash IS NULL OR source_hash ~ '^[0-9a-f]{64}$'),
    disposition text NOT NULL DEFAULT 'unclassified' CHECK (disposition IN ('unclassified','written','skipped')),
    PRIMARY KEY(batch_id,ordinal), UNIQUE(batch_id,memory_id),
    FOREIGN KEY(batch_id,bot_id) REFERENCES memory_core.topic_summary_batches(id,bot_id),
    FOREIGN KEY(memory_id,bot_id) REFERENCES memory_core.memory_items(id,bot_id),
    CHECK ((memory_id IS NULL)=(source_hash IS NULL))
);
CREATE INDEX topic_summary_source_card ON memory_core.topic_summary_sources(bot_id,memory_id)
    WHERE memory_id IS NOT NULL;
REVOKE ALL ON memory_core.topic_summary_batches,memory_core.topic_summary_sources FROM PUBLIC;
REVOKE ALL ON SEQUENCE memory_core.topic_summary_batches_id_seq FROM PUBLIC;
