ALTER TABLE memory_core.source_materials
    ADD COLUMN material_kind text NOT NULL DEFAULT 'chat'
    CHECK (material_kind IN ('chat','memory'));

CREATE TABLE memory_core.import_jobs (
    id uuid PRIMARY KEY,
    bot_id text NOT NULL REFERENCES memory_core.space_policies(bot_id),
    source text NOT NULL CHECK (source IN ('chatgpt','claude','gemini','memory')),
    status text NOT NULL DEFAULT 'preview'
        CHECK (status IN ('preview','queued','running','completed','failed')),
    policy_revision bigint NOT NULL CHECK (policy_revision>0),
    context_digest text NOT NULL,
    model_calls integer NOT NULL DEFAULT 0 CHECK (model_calls>=0),
    usage jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(usage)='array'),
    error_code text,
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    updated_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    UNIQUE(id,bot_id)
);
CREATE INDEX import_jobs_queue ON memory_core.import_jobs(created_at,id)
    WHERE status IN ('queued','running');
CREATE INDEX import_jobs_space ON memory_core.import_jobs(bot_id,created_at DESC,id);

CREATE TABLE memory_core.import_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id uuid NOT NULL,
    bot_id text NOT NULL,
    ordinal integer NOT NULL CHECK (ordinal>=0),
    conversation_key text NOT NULL,
    title text NOT NULL,
    business_date text NOT NULL CHECK (business_date ~ '^\d{4}-\d{2}-\d{2}$'),
    source_key text NOT NULL CHECK (btrim(source_key)<>''),
    message_count integer NOT NULL CHECK (message_count>0),
    segments jsonb CHECK (segments IS NULL OR jsonb_typeof(segments)='array'),
    selected boolean NOT NULL DEFAULT true,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','running','completed','skipped','failed')),
    extraction_id integer,
    error_code text,
    created_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    updated_at text NOT NULL DEFAULT memory_core.format_timestamp(CURRENT_TIMESTAMP),
    UNIQUE(job_id,ordinal),
    FOREIGN KEY(job_id,bot_id) REFERENCES memory_core.import_jobs(id,bot_id),
    FOREIGN KEY(extraction_id,bot_id) REFERENCES memory_core.material_extractions(id,bot_id)
);
CREATE INDEX import_items_progress ON memory_core.import_items(job_id,ordinal);
REVOKE ALL ON memory_core.import_jobs,memory_core.import_items FROM PUBLIC;
REVOKE ALL ON SEQUENCE memory_core.import_items_id_seq FROM PUBLIC;
